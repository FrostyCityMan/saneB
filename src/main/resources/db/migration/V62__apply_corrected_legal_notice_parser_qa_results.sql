    SELECT COUNT(*)
    INTO blocked_count
    FROM local_government_notice_sources
    WHERE semantic_verification_note LIKE '2026-07-28 공식 고시공고 URL 전수 보정:%'
      AND is_enabled = false
      AND deleted_at IS NULL;

    IF enabled_count <> 190 OR blocked_count <> 13 THEN
        RAISE EXCEPTION 'V62 local government QA count mismatch: enabled=%, blocked=%',
            enabled_count, blocked_count;
    END IF;
END
